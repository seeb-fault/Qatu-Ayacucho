import { test, expect } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { resolve } from 'node:path';

const origin='http://127.0.0.1:3100';
test('oficio: propuesta, rechazo, nueva versión y aceptación con horario reservado sin anticipo',async({page,browser})=>{
  const f=JSON.parse(execFileSync(process.execPath,['--env-file-if-exists=.env','--import','tsx','test/reservas/fixture-e2e.ts','--servicio'],{cwd:resolve('../backend'),encoding:'utf8',env:{...process.env,QATU_E2E_RESERVAS:'1'}}));
  expect((await page.request.post('/api/v1/auth/login',{headers:{Origin:origin},data:{email:f.clienteEmail,password:f.password}})).status()).toBe(200);
  await page.goto('/reservas/nueva?publicacion='+f.publicacionId);
  await page.getByLabel('Inicio (hora de Lima)',{exact:true}).fill(new Date(Date.now()+3*86400000).toISOString().slice(0,16));
  await page.getByLabel('Fin (hora de Lima)',{exact:true}).fill(new Date(Date.now()+4*86400000).toISOString().slice(0,16));
  await page.getByLabel('Describe el trabajo',{exact:true}).fill('Instalar cuatro luminarias y revisar los tomacorrientes de mi vivienda.');
  await page.getByRole('button',{name:'Enviar solicitud',exact:true}).click();
  await page.getByRole('link',{name:'Ir a mis solicitudes',exact:true}).click();
  const enviada=page.getByRole('article',{name:f.titulo,exact:true});
  await expect(enviada).toContainText('El proveedor podrá enviarte una propuesta');
  const contexto=await browser.newContext({viewport:{width:360,height:900}});
  try {
    expect((await contexto.request.post(origin+'/api/v1/auth/login',{headers:{Origin:origin},data:{email:f.proveedorEmail,password:f.password}})).status()).toBe(200);
    const proveedor=await contexto.newPage();await proveedor.goto(origin+'/reservas');
    await proveedor.getByRole('button',{name:'Recibidas',exact:true}).click();
    const recibida=proveedor.getByRole('article',{name:f.titulo,exact:true});
    await recibida.getByText('Preparar cotización',{exact:true}).click();
    const formulario=recibida.getByRole('form',{name:'Preparar cotización',exact:true});
    await formulario.getByLabel('Alcance del trabajo',{exact:true}).fill('Instalación de cuatro luminarias y revisión de tomacorrientes.');
    await formulario.getByLabel('Materiales incluidos y exclusiones',{exact:true}).fill('Solo mano de obra; materiales del cliente.');
    await formulario.getByLabel('Importe total (S/)',{exact:true}).fill('180.50');
    await formulario.getByLabel('Vigente hasta (hora de Lima)',{exact:true}).fill(new Date(Date.now()+86400000).toISOString().slice(0,16));
    await formulario.getByRole('button',{name:'Enviar cotización',exact:true}).click();
    await expect(recibida).toContainText('Versión 1');
    await page.getByRole('button',{name:'Actualizar',exact:true}).click();
    await expect(enviada).toContainText('180.50');
    await enviada.getByText('Rechazar esta propuesta',{exact:true}).click();
    await enviada.getByLabel('Motivo para rechazar la cotización',{exact:true}).fill('Necesito que se incluyan los materiales en el importe total.');
    await enviada.getByRole('button',{name:'Rechazar cotización',exact:true}).click();
    await expect(enviada).toContainText('Rechazada por el cliente');
    await proveedor.getByRole('button',{name:'Actualizar',exact:true}).click();
    await recibida.getByText('Preparar nueva versión',{exact:true}).click();
    await formulario.getByLabel('Alcance del trabajo',{exact:true}).fill('Instalación de cuatro luminarias y revisión de tomacorrientes.');
    await formulario.getByLabel('Materiales incluidos y exclusiones',{exact:true}).fill('Incluye materiales y mano de obra para el alcance indicado.');
    await formulario.getByLabel('Importe total (S/)',{exact:true}).fill('250.75');
    await formulario.getByLabel('Vigente hasta (hora de Lima)',{exact:true}).fill(new Date(Date.now()+86400000).toISOString().slice(0,16));
    await formulario.getByRole('button',{name:'Enviar cotización',exact:true}).click();await expect(recibida).toContainText('Versión 2');
    await page.getByRole('button',{name:'Actualizar',exact:true}).click();
    const acuerdo=enviada.getByRole('form',{name:'Aceptar cotización',exact:true});
    await acuerdo.getByRole('checkbox').check();await acuerdo.getByRole('button',{name:'Aceptar cotización',exact:true}).click();
    await expect(enviada).toContainText('Servicio confirmado');
    await expect(enviada).toContainText('Aceptada por el cliente');
    await expect(enviada).toContainText('Horario reservado para esta agenda');
    await page.reload();await expect(enviada).toContainText('250.75');
    const s=(await (await page.request.get('/api/v1/reservas')).json()).items[0];
    expect(s.cotizaciones).toHaveLength(2);expect(s.cotizaciones[1].importeCentimos).toBe(25075);expect(s.cotizaciones[1].respuesta.decision).toBe('ACEPTADA');expect(s.pagoEstado).toBe('PENDIENTE');expect(s.efectivoCentimos).toBe(0);
    expect(s.estado).toBe('SERVICIO_CONFIRMADO');expect(s.venceEn).toBeNull();
    const q=new URLSearchParams({publicacionId:s.publicacionId,inicio:s.inicio,fin:s.fin});
    const disponibilidad=await (await page.request.get('/api/v1/recursos/'+s.recursoId+'/disponibilidad?'+q)).json();expect(disponibilidad.franjas).toHaveLength(1);
    await proveedor.getByRole('button',{name:'Actualizar',exact:true}).click();
    await expect(recibida.getByRole('button',{name:'Enviar cotización',exact:true})).toHaveCount(0);
    expect(await proveedor.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    await proveedor.screenshot({path:'test-results/cotizacion-acordada-360.png',fullPage:true});
  } finally {await contexto.close();}
});
